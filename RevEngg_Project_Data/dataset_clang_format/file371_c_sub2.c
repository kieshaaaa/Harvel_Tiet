#include <stdio.h>

void printUpperCase (  )   { 
  char ch = 'A' ; 
   ; 
  while  ( ch <= 'Z' )   { 
     ; 
    ch++ ; 
   }  ; 
 } 
void printLowerCase (  )   { 
  char ch = 'a' ; 
   ; 
  while  ( ch <= 'z' )   { 
     ; 
    ch++ ; 
   }  ; 
 } 
int entry_point (  )   { 
  printUpperCase (  )  ; 
   ; 
  printLowerCase (  )  ; 
  return 0 ; 
 } 
