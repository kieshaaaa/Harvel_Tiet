#include <stdio.h>
int main() {
    printf("Welcome\nTo\nC Programming");    // Use of \n for new line

    printf("\nWelcome\tTo\tC Programming");  // Use of \t for tab

    printf("\n\'C Programming Language\'");   // Use of \' to print single quote

    printf("\nWelcome\a");      // Use of \a for alert (beep sound)
    return 0;
}