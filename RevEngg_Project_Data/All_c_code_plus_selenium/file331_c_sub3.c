#include <stdio.h>
int main() {
    printf("Programming\nIn\nC");  // Use of \n for new line

    printf("\nTab\tCharacter");    // Use of \t for tab

    printf("\n\"Quotation\"");     // Use of \" to print double quotes

    printf("\nNew\vLine");         // Use of \v for vertical tab
    return 0;
}