/*
 C program to print character without 
 using format specifiers
*/

#include <stdio.h>

int main()
{
    printf("\x41");
    printf("\n");

    printf("\x42");
    printf("\n");

    printf("\x43");
    printf("\n");

    printf("\x44");
    printf("\n");

    return 0;
}
