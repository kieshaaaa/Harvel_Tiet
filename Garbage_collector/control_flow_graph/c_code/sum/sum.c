#include <stdio.h>
int main() {
    int num1, num2, sum;

    // Input the first number
    printf("Enter the first number: ");
    scanf("%d", &num1);

    // Input the second number
    printf("Enter the second number: ");
    scanf("%d", &num2);

    // Perform addition
    sum = num1 + num2;

    // Display the result
    printf("The sum is: %d\n", sum);

    return 0;
}
